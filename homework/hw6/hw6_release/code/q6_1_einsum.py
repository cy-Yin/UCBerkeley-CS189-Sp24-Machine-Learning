import numpy as np

# 6.1.1 
# For a random matrix A of shape(5, 5), find tis trace
A = np.random.rand(5, 5)
# np.einsum
trace_A = np.einsum('ii->', A)
# normal numpy function
trace_A_np = np.trace(A)
print("Section 6.1 q1")
print("A is \n", A)
print("The trace of A calculated by np.einsum              is", trace_A)
print("The trace of A calculated by normal numpy functions is", trace_A_np)
print("Error of two results is", np.abs(trace_A - trace_A_np))
print("\n")

# 6.1.2
# For random matrices A, B which both have the shape of (5, 5),
# compute their matrix product.
A = np.random.rand(5, 5)
B = np.random.rand(5, 5)
# np.einsum
product_AB = np.einsum('ik,kj->ij', A, B)
# normal numpy function
product_AB_np = np.dot(A, B)
print("Section 6.1 q2")
print("A is \n", A)
print("B is \n", B)
print("A, B's matrix product calculated by np.einsum is\n", product_AB)
print("A, B's matrix product calculated by normal numpy functions is\n", product_AB_np)
print("Error of two results is", np.linalg.norm(product_AB) - np.linalg.norm(product_AB_np))
print("\n")

# 6.1.2
# For a batch of random matrices of shapes (3, 4, 5) and (3, 5, 6) (the batch size is 3 here),
# compute their batchwise matrix product (the resulting batch will have shape (3, 4, 6)).
A = np.random.rand(3, 4, 5)
B = np.random.rand(3, 5, 6)
# np.einsum
batchwise_product_AB = np.einsum('ijl,ilk->ijk', A, B)
# normal numpy function
batchwise_product_AB_np = np.matmul(A, B)
print("Section 6.1 q3")
print("A is \n", A)
print("B is \n", B)
print("A, B's matrix product calculated by np.einsum is\n", batchwise_product_AB)
print("A, B's matrix product calculated by normal numpy functions is\n", batchwise_product_AB_np)
print("A, B's matrix product calculated by np.einsum              " \
                                        "has the shape of", batchwise_product_AB.shape)
print("A, B's matrix product calculated by normal numpy functions " \
                                        "has the shape of", batchwise_product_AB_np.shape)
print("Error of two results is", 
      np.linalg.norm(batchwise_product_AB) - np.linalg.norm(batchwise_product_AB_np))
print("\n")



